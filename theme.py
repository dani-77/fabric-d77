"""Wallpaper-following palette, blended over the hardcoded style.css colors.

style.css stays the source of truth: its ``:vars`` block is the startup
palette and the fallback. On top of it, a palette generated by matugen
from the current wallpaper (~/.cache/d77/palette.json) is blended in by a
single "mix" value:
    0.0 = style.css colors untouched, 1.0 = wallpaper palette.
The mix is the slider in the wallpaper picker, persisted to
~/.config/d77/theme-mix.

palette.json and theme-mix are shared with utumno and quickshell-d77 (keys
match their config/Colors.qml). Since fabric-d77's ``--colorN`` variables
are pywal-style slots rather than named roles, VAR_MAP below says which
palette token each one follows.
"""

import json
import os
import re
import subprocess

from gi.repository import Gio, GLib

import wallpaper_state

PALETTE_DIR = os.path.expanduser("~/.cache/d77")
PALETTE_FILE = os.path.join(PALETTE_DIR, "palette.json")
MIX_DIR = os.path.expanduser("~/.config/d77")
MIX_FILE = os.path.join(MIX_DIR, "theme-mix")

MATUGEN_CONFIG = os.path.join(os.path.dirname(os.path.abspath(__file__)), "theme", "matugen.toml")

# style.css variable -> palette.json token. Variables not listed here (or
# whose value isn't a plain #rrggbb, e.g. alpha(...)) keep their style.css
# value; derived ones like --window-bg follow automatically.
VAR_MAP = {
    "background": "bg",
    "foreground": "fg",
    "color0": "bg",
    "color1": "bgHighlight",  # hover backgrounds
    "color2": "green",
    "color3": "blue",  # occupied (inactive) workspaces
    "color4": "cyan",  # secondary accent (brightness, weather, network)
    "color5": "magenta",
    "color6": "blue",  # main accent (icons, focus outlines)
    "color7": "fg",
    "color8": "comment",  # muted text
    "color9": "magenta",  # active workspace, window borders
    "color10": "green",
    "color11": "magenta",  # menu/tooltip/OSD borders
    "color12": "red",  # urgent workspace
    "color13": "magenta",
    "color14": "blue",
    "color15": "fg",
    "red": "red",
    "green": "green",
    "comment": "comment",
    "thumb-selected": "cyan",
}

_VARS_BLOCK = re.compile(r":vars\s*{([^}]*)}")
_HEX_DECL = re.compile(r"(--([\w-]+)\s*:\s*)(#[0-9a-fA-F]{6})(\s*;)")

_app = None
_css_path: str | None = None
_last_css: str | None = None
_monitors: list = []
_reload_source: int | None = None
_save_source: int | None = None


def _read_mix() -> float:
    try:
        with open(MIX_FILE, "r") as f:
            return max(0.0, min(1.0, float(f.read().strip())))
    except (OSError, ValueError):
        return 0.0


def _read_palette() -> dict:
    try:
        with open(PALETTE_FILE, "r") as f:
            data = json.load(f)
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


_mix = _read_mix()
_palette = _read_palette()


def get_mix() -> float:
    return _mix


def palette_valid() -> bool:
    """A palette generated for another wallpaper (or for none, after
    "Clear") is stale and must not tint the shell."""
    source = _palette.get("source")
    return bool(source) and source == wallpaper_state.read_current()


def _blend(base_hex: str, target_hex, t: float) -> str:
    if not isinstance(target_hex, str) or not re.fullmatch(r"#[0-9a-fA-F]{6}", target_hex):
        return base_hex
    a = [int(base_hex[i : i + 2], 16) for i in (1, 3, 5)]
    b = [int(target_hex[i : i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(a, b))


def build_css(css_text: str) -> str:
    """Returns style.css with its :vars hex values blended toward the
    wallpaper palette (unchanged when mix is 0 or the palette is stale)."""
    t = _mix if palette_valid() else 0.0
    if t <= 0.0:
        return css_text

    def blend_decl(m: re.Match) -> str:
        token = VAR_MAP.get(m.group(2))
        if token is None:
            return m.group(0)
        return m.group(1) + _blend(m.group(3), _palette.get(token), t) + m.group(4)

    return _VARS_BLOCK.sub(
        lambda m: ":vars {" + _HEX_DECL.sub(blend_decl, m.group(1)) + "}",
        css_text,
        count=1,
    )


def apply():
    """(Re)applies the stylesheet if the blended result changed."""
    global _last_css
    if _app is None or _css_path is None:
        return
    try:
        with open(_css_path, "r") as f:
            css = build_css(f.read())
    except OSError as exc:
        print(f"[theme] can't read {_css_path}: {exc}")
        return
    if css == _last_css:
        return
    _last_css = css
    _app.set_stylesheet_from_string(css, base_path=os.path.dirname(_css_path))


def _schedule_reload(delay_ms: int = 60):
    """Coalesces bursts (slider drags, rename events) into one restyle."""
    global _reload_source
    if _reload_source is not None:
        return

    def run():
        global _reload_source, _palette, _mix
        _reload_source = None
        _palette = _read_palette()
        apply()
        return False

    _reload_source = GLib.timeout_add(delay_ms, run)


def set_mix(value: float):
    """Live preview: restyles right away, persists after the slider settles."""
    global _mix, _save_source
    _mix = max(0.0, min(1.0, value))
    _schedule_reload(30)

    if _save_source is not None:
        GLib.source_remove(_save_source)

    def save():
        global _save_source
        _save_source = None
        try:
            os.makedirs(MIX_DIR, exist_ok=True)
            tmp = MIX_FILE + ".tmp"
            with open(tmp, "w") as f:
                f.write(f"{_mix:.2f}\n")
            os.replace(tmp, MIX_FILE)
        except OSError as exc:
            print(f"[theme] can't save mix: {exc}")
        return False

    _save_source = GLib.timeout_add(400, save)


def refresh():
    """Re-reads palette.json and restyles (e.g. after Clear, when the
    wallpaper changed but the palette file didn't)."""
    _schedule_reload()


def generate_palette(path: str):
    """Runs matugen for `path` in the background. The file monitor picks up
    the new palette.json once it lands.

    --source-color-index 0 is required: without a TTY, matugen 4.x aborts
    with "Multiple source colors found" on most images. The template writes
    palette.json.tmp and it is renamed here, so readers never see a
    half-written file.
    """
    if not os.path.isfile(MATUGEN_CONFIG):
        return
    script = (
        'mkdir -p "$3" && matugen -c "$1" image "$2" '
        "--source-color-index 0 -t scheme-vibrant -m dark -q >/dev/null 2>&1 "
        '&& mv -f "$3/palette.json.tmp" "$3/palette.json"'
    )
    try:
        subprocess.Popen(
            ["sh", "-c", script, "sh", MATUGEN_CONFIG, path, PALETTE_DIR],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
    except FileNotFoundError:
        pass


def _on_dir_changed(_monitor, file, other_file, _event):
    global _mix
    names = {f.get_basename() for f in (file, other_file) if f is not None}
    if "palette.json" in names:
        _schedule_reload()
    elif "theme-mix" in names:
        new_mix = _read_mix()
        # Our own save echoing back; don't fight an in-progress drag.
        if _save_source is None and abs(new_mix - _mix) > 1e-3:
            _mix = new_mix
            _schedule_reload()


def init(app, css_path: str):
    """Applies the stylesheet and starts following palette/mix changes."""
    global _app, _css_path
    _app = app
    _css_path = css_path

    for d in (PALETTE_DIR, MIX_DIR):
        try:
            os.makedirs(d, exist_ok=True)
            mon = Gio.File.new_for_path(d).monitor_directory(Gio.FileMonitorFlags.WATCH_MOVES, None)
            mon.connect("changed", _on_dir_changed)
            _monitors.append(mon)
        except (OSError, GLib.Error) as exc:
            print(f"[theme] can't watch {d}: {exc}")

    apply()

    # palette.json is shared with the QML shells: if it was last generated
    # for another wallpaper (e.g. utumno's), regenerate it for ours.
    current = wallpaper_state.read_current()
    if current and not palette_valid():
        generate_palette(current)
